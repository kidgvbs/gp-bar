#!/usr/bin/env bash
#
# Build SMProbe.app: compile both binaries, assemble the bundle, generate
# the LaunchDaemon plist (via `smprobe make-plist`), then seal everything
# with an ad-hoc signature and verify the result.
#
# Order matters (the 21/10 baseline): the plist is written BEFORE the
# codesign step, so BTM always sees it as a sealed resource. A plist added
# after signing is rejected with -67054 "Codesigning failure loading
# plist" (anomaly B).
#
# Everything here is argv-safe (review B4): no command is assembled from
# strings, every path is quoted, no `eval`.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
APP="$ROOT/build/SMProbe.app"
BIN="$ROOT/target/release"
PLIST_RELATIVE="Library/LaunchDaemons/dev.gpbar.smprobe.helper.plist"

echo "==> cargo build --release --locked"
cargo build --release --locked --manifest-path "$ROOT/Cargo.toml"

echo "==> assembling $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Library/LaunchDaemons"
cp "$BIN/smprobe" "$BIN/smprobe-helper" "$APP/Contents/MacOS/"

# No LSUIElement: the app must default to the Regular activation policy,
# or the SMAppService authorization prompt cannot anchor (anomaly A).
cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key>
	<string>en</string>
	<key>CFBundleExecutable</key>
	<string>smprobe</string>
	<key>CFBundleIdentifier</key>
	<string>dev.gpbar.smprobe</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>SMProbe</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleShortVersionString</key>
	<string>2.0.0</string>
	<key>CFBundleVersion</key>
	<string>2</string>
	<key>LSMinimumSystemVersion</key>
	<string>13.0</string>
</dict>
</plist>
PLIST

# The plist is generated by Rust code (xml-escaped by construction, unit
# tested) and written into the bundle at BUILD time, before signing.
#
# NOTE (observed on macOS 27.2): a process exec'd from a freshly assembled
# .app bundle gets EIO when writing into that same bundle — the exec-from
# and write-into factors are each fine alone, only the combination fails.
# So the generator runs from target/release (byte-identical to the bundle
# copy: same `cp` source) and the shell (outside the bundle) writes the
# file. This is one more reason the real app must never write inside its
# own bundle at runtime.
"$BIN/smprobe" make-plist "$APP" \
  > "$APP/Contents/$PLIST_RELATIVE"

# Ad-hoc signature, matching the 21/10 baseline for comparability (no
# Hardened Runtime options; production signing decisions come later).
echo "==> ad-hoc codesign (identifier dev.gpbar.smprobe)"
codesign --force --sign - --identifier dev.gpbar.smprobe "$APP"

echo "==> verification"
codesign --verify --verbose=2 "$APP" 2>&1
codesign -dv "$APP" 2>&1 | sed 's/^/    /'
plutil -lint "$APP/Contents/$PLIST_RELATIVE"
if grep -q "Library/LaunchDaemons/dev.gpbar.smprobe.helper.plist" \
  "$APP/Contents/_CodeSignature/CodeResources"; then
  echo "OK: the daemon plist is sealed into the bundle signature"
else
  echo "FAIL: the daemon plist is NOT in _CodeSignature/CodeResources" >&2
  exit 1
fi

# spctl --assess is intentionally NOT a gate: an ad-hoc signature fails it
# by design.
echo
echo "SMProbe.app is ready: $APP"
echo "Next steps (human): see smprobe/PROTOCOL.md"
