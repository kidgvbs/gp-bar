#!/usr/bin/env bash
#
# Build AND install SMProbe.app in one command: compile both binaries,
# assemble the bundle DIRECTLY at the destination path, generate the
# LaunchDaemon plist with the INSTALLED copy's paths (via
# `smprobe make-plist <dest>`), then seal everything with an ad-hoc
# signature and verify the result at the destination.
#
# Usage: bash build-probe.sh "$HOME/Applications/SMProbe.app"
#
# The plist must be generated against the DESTINATION path, never the
# build tree: launchd would otherwise execute the helper from the
# worktree staging copy (user-writable, moved by rebuilds and
# `git clean`) — the stable-path discipline broken for the daemon.
#
# Order matters (the 21/10 baseline): the plist is written BEFORE the
# codesign step, so BTM always sees it as a sealed resource. A plist added
# after signing is rejected with -67054 "Codesigning failure loading
# plist" (anomaly B).
#
# Everything here is argv-safe (review B4): no command is assembled from
# strings, every path is quoted, no `eval`.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
BIN="$ROOT/target/release"
PLIST_RELATIVE="Library/LaunchDaemons/dev.gpbar.smprobe.helper.plist"

DEST="${1:-}"
if [[ -z "$DEST" ]]; then
  echo "usage: $0 <destination-bundle>   (e.g. \"\$HOME/Applications/SMProbe.app\")" >&2
  exit 2
fi
# Safety rails: destination must be absolute and be exactly `SMProbe.app`.
if [[ "$DEST" != /* ]]; then
  echo "FAIL: the destination must be an ABSOLUTE path, got: $DEST" >&2
  exit 2
fi
if [[ "$(basename -- "$DEST")" != "SMProbe.app" ]]; then
  echo "FAIL: the destination basename must be exactly SMProbe.app, got: $DEST" >&2
  exit 2
fi

echo "==> cargo build --release --locked"
cargo build --release --locked --manifest-path "$ROOT/Cargo.toml"

echo "==> installing the bundle at $DEST"
echo "==> rm -rf \"$DEST\" (this is your install action; the path is the one you passed)"
rm -rf "$DEST"
mkdir -p "$DEST/Contents/MacOS" "$DEST/Contents/Library/LaunchDaemons"
cp "$BIN/smprobe" "$BIN/smprobe-helper" "$DEST/Contents/MacOS/"

# No LSUIElement: the app must default to the Regular activation policy,
# or the SMAppService authorization prompt cannot anchor (anomaly A).
cat > "$DEST/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key>
	<string>en</string>
	<key>CFBundleExecutable</key>
	<string>smprobe</string>
	<key>CFBundleIdentifier</key>
	<string>dev.gpbar.smprobe</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>SMProbe</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleShortVersionString</key>
	<string>2.0.0</string>
	<key>CFBundleVersion</key>
	<string>2</string>
	<key>LSMinimumSystemVersion</key>
	<string>13.0</string>
</dict>
</plist>
PLIST

# The plist is generated by Rust code (xml-escaped by construction, unit
# tested) with the DESTINATION paths (never the build tree), and is
# written into the bundle BEFORE signing.
#
# NOTE (observed on macOS 27.2): a process exec'd from a freshly assembled
# .app bundle gets EIO when writing into that same bundle — the exec-from
# and write-into factors are each fine alone, only the combination fails.
# So the generator runs from target/release (byte-identical to the bundle
# copy: same `cp` source) and the shell (outside the bundle) writes the
# file. This is one more reason the real app must never write inside its
# own bundle at runtime.
"$BIN/smprobe" make-plist "$DEST" \
  > "$DEST/Contents/$PLIST_RELATIVE"

# Ad-hoc signature, matching the 21/10 baseline for comparability (no
# Hardened Runtime options; production signing decisions come later).
echo "==> ad-hoc codesign (identifier dev.gpbar.smprobe)"
codesign --force --sign - --identifier dev.gpbar.smprobe "$DEST"

echo "==> verification at $DEST"
codesign --verify --verbose=2 "$DEST" 2>&1
codesign -dv "$DEST" 2>&1 | sed 's/^/    /'
plutil -lint "$DEST/Contents/$PLIST_RELATIVE"
if grep -q "Library/LaunchDaemons/dev.gpbar.smprobe.helper.plist" \
  "$DEST/Contents/_CodeSignature/CodeResources"; then
  echo "OK: the daemon plist is sealed into the bundle signature"
else
  echo "FAIL: the daemon plist is NOT in _CodeSignature/CodeResources" >&2
  exit 1
fi

# spctl --assess is intentionally NOT a gate: an ad-hoc signature fails it
# by design.
echo
echo "SMProbe.app is installed at: $DEST"
echo "Next steps (human): see smprobe/PROTOCOL.md"